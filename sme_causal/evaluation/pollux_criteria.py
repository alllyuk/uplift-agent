EVALUATION_CRITERIA = {
    "Глубина проработки ответа": DEPTH_OF_ANALYSIS,
    "Отсутствие избыточной информации (воды)": ABSENCE_OF_REDUNDANCY,
    "Формальный учет требований из запроса пользователя": FORMAL_REQUIREMENTS,
    "Применимость": PRACTICAL_APPLICABILITY,
    "Последовательность и логичность": CONSISTENCY_AND_LOGIC,
}

CRITERIA_NAMES = list(EVALUATION_CRITERIA.keys())


def get_criteria(name: str) -> Optional[CriteriaItem]:
    """Get criteria by name.

    Args:
        name: Criteria name.

    Returns:
        CriteriaItem or None if not found.
    """
    return EVALUATION_CRITERIA.get(name)


def get_all_criteria() -> dict:
    """Get all evaluation criteria.

    Returns:
        Dictionary with all criteria items.
    """
    return EVALUATION_CRITERIA.copy()
