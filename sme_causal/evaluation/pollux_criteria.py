"""
Evaluation criteria for Pollux-based assessment of uplift agent responses.

This module defines all criteria used for evaluating causal analysis and what-if
scenario explanations generated by the CausalAgent.

## Structure

- **CriteriaItem**: Dataclass with fields:
  - criteria_name: Official name of the criterion
  - criteria_description: Full description including background and details
  - rubrics: Scoring scale (0, 1, 2) with descriptions for each score

## Usage Examples

### Get all criteria:
    from sme_causal.evaluation.pollux_criteria import get_all_criteria, CRITERIA_NAMES

    criteria_dict = get_all_criteria()
    for name in CRITERIA_NAMES:
        print(name)

### Get specific criterion:
    from sme_causal.evaluation.pollux_criteria import get_criteria

    depth_criteria = get_criteria("Глубина проработки ответа")
    if depth_criteria:
        print(depth_criteria.rubrics)

### Direct access:
    from sme_causal.evaluation.pollux_criteria import EVALUATION_CRITERIA

    criteria = EVALUATION_CRITERIA["Применимость"]
    print(criteria.criteria_description)
"""

from dataclasses import dataclass
from typing import Optional


@dataclass
class CriteriaItem:
    """Single criteria specification for Pollux evaluation."""
    criteria_name: str
    criteria_description: str
    rubrics: str


DEPTH_OF_ANALYSIS = CriteriaItem(
    criteria_name="Глубина проработки ответа",
    criteria_description=(
        "Данный критерий оценивает глубину проработки ответа (в зависимости от запроса пользователя):\n"
        "— Модель выдает ответ с необходимой степенью детализации и, если требуется, анализа, демонстрирует полноту изложения.\n"
        "— Модель достигает максимальной степени проработки, точности и ясности.\n\n"
        "Уточнения:\n"
        "— Глубина анализа: уровень проработки и детализации, с которым модель исследует содержание.\n"
        "— Выявление взаимосвязей: способность выявлять сложные взаимосвязи между компонентами (график, RAG, PSM).\n"
        "— Интеграция источников: умение комбинировать информацию из разных источников для полного анализа.\n"
        "— Обоснованность выводов: каждый вывод должен быть подкреплен анализом данных.\n"
        "\n"
        "ВНИМАНИЕ: в этом критерии мы НЕ учитываем наличие избыточной информации (воды)."
    ),
    rubrics=(
        "0: В ответе модели очень поверхностный анализ, отсутствует глубокая проработка. "
        "Модель не раскрывает взаимосвязи между источниками.\n"
        "1: Модель демонстрирует приемлемую степень проработки, но ответу не хватает глубины и/или детализации. "
        "Некоторые взаимосвязи пропущены.\n"
        "2: Ответ модели отлично проработан, есть глубина, анализ и достаточно деталей. "
        "Все компоненты интегрированы в единый анализ с четкими выводами."
    ),
)

ABSENCE_OF_REDUNDANCY = CriteriaItem(
    criteria_name="Отсутствие избыточной информации (воды)",
    criteria_description=(
        "Данный критерий оценивает способность модели писать только по существу.\n\n"
        "В ответе модели все элементы должны способствовать раскрытию темы и достижению цели. "
        "Ответ модели может быть глубоко проработанным и полезным, но в нем все еще может быть избыточность (вода). "
        "Под избыточной информацией, или водой, понимается информация, которую можно убрать из ответа модели "
        "без потери смысла и целостности повествования.\n\n"
        "Примеры избыточности:\n"
        "— Повторение одних и тех же идей разными словами\n"
        "— Общие рассуждения, не связанные с конкретным анализом\n"
        "— Излишние предисловия и заключения\n"
        "— Информация, не подтвержденная данными из источников"
    ),
    rubrics=(
        "0: В ответе модели очень много избыточной информации (воды). "
        "Кажется, что модель льет воду, чтобы написать необходимое количество знаков.\n"
        "1: В ответе модели приемлемое количество избыточной информации, но хотелось бы меньше. "
        "В целом все по существу, но встречаются идеи, которые не способствуют раскрытию темы.\n"
        "2: В ответе модели все по существу. Нет (или практически нет) воды, все фразы способствуют раскрытию темы."
    ),
)

